"""Export reproducible, synthetic rule results for the server-free showcase."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tradepilot.demos import demo_documents
from tradepilot.engine import extract, review
from tradepilot.parsers import parse_document
from tradepilot.schema import Policy


def snapshots():
    result = {}
    for variant in ("conflict", "normal", "missing", "payment"):
        documents = []
        for kind, name, text in demo_documents(variant):
            blocks, warnings = parse_document(name, text.encode())
            doc = {"id": kind, "kind": kind, "name": name, "blocks": blocks, "warnings": warnings}
            doc["facts"] = extract(doc)
            for fact in doc["facts"]:
                fact["id"] = f"{kind}:{fact['field']}:{fact['evidence']['block_id']}"
            documents.append(doc)
        policy = Policy().model_dump()
        findings = review(documents, ["quote"], policy)
        for finding in findings:
            finding["id"] = hashlib.sha256(finding["key"].encode()).hexdigest()[:16]
        result[variant] = {"synthetic": True, "engine": "rules-only", "policy": policy,
                           "documents": documents, "findings": findings}
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = "// Generated by scripts/build_preview.py from the real Python rule engine.\n"
    text += "globalThis.TRADEPILOT_CASES = " + json.dumps(snapshots(), ensure_ascii=False, indent=2) + ";\n"
    path = ROOT / "showcase/cases.js"
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit("Showcase is stale. Run python scripts/build_preview.py and commit cases.js")
        print("Showcase matches the current deterministic engine")
    else:
        path.parent.mkdir(exist_ok=True)
        path.write_text(text)


if __name__ == "__main__":
    main()
